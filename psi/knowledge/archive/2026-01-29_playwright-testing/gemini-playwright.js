#!/usr/bin/env node

/**
 * Matrix Gemini Parallel Research - Playwright Edition
 *
 * Uses Playwright's persistent context for multiple windows with shared auth.
 *
 * Usage:
 *   node gemini-playwright.js "query1" "query2" "query3" "query4"
 *   node gemini-playwright.js --headless "query1" "query2"
 */

const { chromium } = require('playwright');
const fs = require('fs').promises;
const path = require('path');
const os = require('os');
const { exec } = require('child_process');
const util = require('util');

const execPromise = util.promisify(exec);

// ============================================================================
// Human Mimicry Helpers
// ============================================================================

function randomDelay(min, max) {
  return Math.floor(Math.random() * (max - min + 1)) + min;
}

async function humanWait(page, minMs = 1000, maxMs = 3000) {
  await page.waitForTimeout(randomDelay(minMs, maxMs));
}

// ============================================================================
// Configuration
// ============================================================================

const CONFIG = {
  BROWSER_PATH: '/Applications/Brave Browser.app/Contents/MacOS/Brave Browser',
  GEMINI_URL: 'https://gemini.google.com/app',
  MATRIX_INBOX: path.join(process.env.HOME, 'workspace/The-matrix/psi/learn/inbox'),
  VOICE_SCRIPT: path.join(process.env.HOME, 'workspace/The-matrix/psi/matrix/voice.sh'),

  // Persistent profile for auth
  USER_DATA_DIR: path.join(process.env.HOME, '.gemini-automation-profile'),

  // Parallel settings (use 1 for sequential to avoid detection)
  MAX_CONCURRENT: 1,
  NAV_TIMEOUT: 60000,       // 60 seconds for navigation
  RESPONSE_TIMEOUT: 45000,  // 45 seconds for Gemini response
  STAGGER_DELAY: 1500,      // 1.5s delay between window navigations

  // Selectors (Gemini 2024/2025 UI)
  SELECTORS: {
    promptBox: [
      'rich-textarea[placeholder*="Enter"]',
      'div[contenteditable="true"]',
      'textarea[placeholder*="Enter"]',
      '.ql-editor',
      'textarea'
    ],
    // Wait for response indicators
    responseIndicator: [
      'message-content',
      '.response-container',
      '.model-response-text',
      'model-response'
    ]
  }
};

// ============================================================================
// Voice
// ============================================================================

async function speak(message, agent = 'Morpheus') {
  try {
    await execPromise(`sh "${CONFIG.VOICE_SCRIPT}" "${message}" "${agent}"`);
  } catch {
    console.log(`🔇 ${message}`);
  }
}

// ============================================================================
// Save to Inbox
// ============================================================================

async function saveToInbox(query, response, metadata = {}) {
  const timestamp = new Date().toISOString();
  const slug = query.toLowerCase().replace(/[^\w\s-]/g, '').replace(/\s+/g, '_').substring(0, 50);
  const filename = `gemini_${slug}_${timestamp.replace(/[:.]/g, '-')}.md`;
  const filePath = path.join(CONFIG.MATRIX_INBOX, filename);

  const markdown = `# Gemini Research: ${query}

> **Date:** ${timestamp}
> **Source:** Playwright Parallel Research
> **Agent:** Morpheus
${metadata.windowIndex !== undefined ? `> **Window:** ${metadata.windowIndex}` : ''}

## Query

${query}

## Response

${response}

---

*Generated by Matrix Gemini Playwright Research Tool*
`;

  await fs.writeFile(filePath, markdown);
  console.log(`✅ Saved: ${filename}`);
  return { filename, filePath };
}

// ============================================================================
// Research a Single Query
// ============================================================================

async function researchQuery(page, query, index, staggerMs = 0) {
  const startTime = Date.now();

  // Stagger the start with randomized delay to look human
  if (staggerMs > 0) {
    const jitteredDelay = staggerMs + randomDelay(-500, 500);
    await page.waitForTimeout(Math.max(0, jitteredDelay));
  }

  console.log(`🚀 Window ${index}: Starting "${query}"`);

  try {
    // Navigate to Gemini - use 'load' instead of 'networkidle' for reliability
    await page.goto(CONFIG.GEMINI_URL, {
      waitUntil: 'domcontentloaded',
      timeout: CONFIG.NAV_TIMEOUT
    });

    // Wait for page to stabilize
    await page.waitForTimeout(3000);
    console.log(`📍 Window ${index}: Page loaded, looking for prompt...`);

    // Find prompt box with multiple attempts
    let promptElement = null;
    for (const selector of CONFIG.SELECTORS.promptBox) {
      try {
        promptElement = await page.waitForSelector(selector, {
          timeout: 8000,
          state: 'visible'
        });
        if (promptElement) {
          console.log(`📝 Window ${index}: Found prompt with selector: ${selector}`);
          break;
        }
      } catch {}
    }

    if (!promptElement) {
      // Debug: Take screenshot and log page content
      const screenshot = `/tmp/gemini_debug_${index}.png`;
      await page.screenshot({ path: screenshot });
      console.log(`📸 Window ${index}: Debug screenshot saved to ${screenshot}`);
      throw new Error('Could not find prompt input - check screenshot');
    }

    // Click to focus, then type like a human
    await promptElement.click();
    await page.waitForTimeout(randomDelay(300, 800));

    // Type with human-like delays (50-150ms between keystrokes)
    await promptElement.type(query, { delay: randomDelay(50, 120) });
    await page.waitForTimeout(randomDelay(400, 900));
    await page.keyboard.press('Enter');

    console.log(`⏳ Window ${index}: Query submitted, waiting for response...`);

    // Wait for response with polling (more reliable than fixed timeout)
    let response = '';
    const pollStart = Date.now();
    const maxWait = CONFIG.RESPONSE_TIMEOUT;

    while (Date.now() - pollStart < maxWait) {
      await page.waitForTimeout(2000);

      // Check for response content
      response = await page.evaluate(() => {
        // Try multiple selectors for Gemini's response
        const selectors = [
          'message-content',
          '.response-container',
          '.model-response-text',
          'model-response',
          '[data-message-author-role="model"]',
          '.markdown-body'
        ];

        for (const sel of selectors) {
          const els = document.querySelectorAll(sel);
          if (els.length > 0) {
            // Get the last (most recent) response
            const lastEl = els[els.length - 1];
            const text = lastEl.innerText?.trim();
            if (text && text.length > 20) return text;
          }
        }

        // Fallback: look for any substantial text in main area
        const main = document.querySelector('main');
        if (main) {
          const text = main.innerText;
          // Check if there's content beyond just the prompt
          if (text.length > 200) return text.substring(0, 8000);
        }
        return '';
      });

      // Check if we got a meaningful response
      if (response.length > 50 && !response.includes('Enter a prompt')) {
        break;
      }
    }

    if (!response || response.length < 50) {
      throw new Error('No meaningful response received');
    }

    const duration = Date.now() - startTime;
    console.log(`✅ Window ${index}: Response received (${duration}ms)`);
    console.log(`   Preview: ${response.substring(0, 100)}...`);

    await saveToInbox(query, response, { windowIndex: index, duration });

    return { query, success: true, response };

  } catch (error) {
    console.error(`❌ Window ${index}: Error - ${error.message}`);
    return { query, success: false, error: error.message };
  }
}

// ============================================================================
// Main
// ============================================================================

async function main() {
  const args = process.argv.slice(2);
  const headless = args.includes('--headless');
  const queries = args.filter(a => !a.startsWith('--'));

  if (queries.length === 0) {
    console.log(`
🔮 Matrix Gemini Playwright Research

Usage:
  node gemini-playwright.js "query1" "query2" "query3"
  node gemini-playwright.js --headless "query1" "query2"

Features:
  - Multiple windows with SHARED authentication
  - Persistent profile (login once, remembered forever)
  - True parallel execution
`);
    process.exit(1);
  }

  await speak(`Morpheus online. Opening ${queries.length} parallel Gemini windows.`);

  console.log(`\n🔮 Matrix Gemini Playwright Research`);
  console.log(`📊 Queries: ${queries.length}`);
  console.log(`👁️  Mode: ${headless ? 'headless' : 'visible'}`);
  console.log(`🔐 Profile: ${CONFIG.USER_DATA_DIR}`);
  console.log('');

  // Launch with MINIMAL flags - let Brave look as normal as possible
  const context = await chromium.launchPersistentContext(CONFIG.USER_DATA_DIR, {
    headless,
    executablePath: CONFIG.BROWSER_PATH,
    args: [
      '--disable-blink-features=AutomationControlled'
    ],
    ignoreDefaultArgs: ['--enable-automation', '--enable-blink-features=IdleDetection'],
    viewport: null  // Use default viewport, don't override
  });

  // Minimal stealth - just hide webdriver
  await context.addInitScript(() => {
    Object.defineProperty(navigator, 'webdriver', { get: () => false });
  });

  try {
    // Create a page for each query (up to MAX_CONCURRENT)
    const numWindows = Math.min(queries.length, CONFIG.MAX_CONCURRENT);
    const pages = [];

    // Get first page and create additional ones
    pages.push(context.pages()[0] || await context.newPage());
    for (let i = 1; i < numWindows; i++) {
      pages.push(await context.newPage());
    }

    console.log(`📱 Opened ${pages.length} windows\n`);

    // Process queries in batches with STAGGERED navigation
    const results = [];
    for (let batch = 0; batch < queries.length; batch += numWindows) {
      const batchQueries = queries.slice(batch, batch + numWindows);

      // Run batch in parallel with staggered starts
      // This prevents all windows hitting Gemini at the exact same moment
      const batchPromises = batchQueries.map((query, i) => {
        const pageIndex = i % pages.length;
        const staggerDelay = i * CONFIG.STAGGER_DELAY;  // Stagger each window
        return researchQuery(pages[pageIndex], query, batch + i, staggerDelay);
      });

      const batchResults = await Promise.all(batchPromises);
      results.push(...batchResults);
    }

    // Summary
    const successful = results.filter(r => r.success).length;
    console.log(`\n✅ Complete: ${successful}/${queries.length} queries successful`);
    console.log(`📁 Results: ${CONFIG.MATRIX_INBOX}\n`);

    await speak(`Research complete. ${successful} of ${queries.length} queries successful.`);

  } finally {
    await context.close();
  }
}

main().catch(err => {
  console.error('Fatal error:', err);
  process.exit(1);
});
